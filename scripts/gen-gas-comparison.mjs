#!/usr/bin/env node
// Regenerates GAS_COMPARISON.md from live measurements.
//
// Runs each package's `scripts/measure-gas.ts` under its own hardhat (which recompiles first, so it
// always reflects the current contracts), collects the `DATA ...` lines they print, and rewrites
// GAS_COMPARISON.md. Re-run this whenever the tree contracts change.
//
//   node scripts/gen-gas-comparison.mjs      (or: yarn gas:compare)
//
import { execFileSync } from "node:child_process"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const HARDHAT = join(ROOT, "node_modules", ".bin", "hardhat")

const PKGS = [
    { label: "Lean", dir: "lean-imt" },
    { label: "Skinny", dir: "skinny-imt" },
    { label: "Fat", dir: "fat-imt" }
]

// --- run each package's measurement, collect DATA lines -------------------------------------------
const dataLines = []
for (const { label, dir } of PKGS) {
    const cwd = join(ROOT, "packages", dir)
    console.error(`\n▶ measuring ${dir} (compiles + runs scenarios, ~1-2 min)…`)
    const stdout = execFileSync(HARDHAT, ["run", "scripts/measure-gas.ts"], {
        cwd,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "inherit"],
        maxBuffer: 64 * 1024 * 1024
    })
    const lines = stdout.split("\n").filter((l) => l.startsWith("DATA "))
    if (lines.length === 0) throw new Error(`no DATA lines from ${dir} — measurement failed`)
    dataLines.push(...lines)
    console.error(`  ✓ ${label}: ${lines.length} line(s)`)
}

// --- parse ----------------------------------------------------------------------------------------
// "DATA Lean {json}"  |  "DATA Skinny Poseidon Bare {json}"
let LEAN = null
const DATA = { skinny: {}, fat: {} } // DATA[pkg][Hash][Version] = {scenario: gas}
for (const line of dataLines) {
    const rest = line.slice("DATA ".length)
    const jsonAt = rest.indexOf("{")
    const head = rest.slice(0, jsonAt).trim().split(/\s+/)
    const obj = JSON.parse(rest.slice(jsonAt))
    const nums = Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, Number(v)]))
    if (head[0] === "Lean") {
        LEAN = nums
    } else {
        const pkg = head[0].toLowerCase() // skinny | fat
        const [, hash, version] = head
        ;(DATA[pkg][hash] ||= {})[version] = nums
    }
}
if (!LEAN) throw new Error("missing Lean baseline data")

// --- format ---------------------------------------------------------------------------------------
const KEYS = ["insert128", "insertMany18", "insertManyRepeated128", "update144", "updateMany8"]
const ROWLBL = {
    insert128: "insert · 128th leaf (deep)",
    insertMany18: "insertMany · 18 into 126-tree",
    insertManyRepeated128: "insertManyRepeated · 128 one call ‡",
    update144: "update · leaf @ index 0 of 144-tree",
    updateMany8: "updateMany · 8 in size-8 tree"
}
const HASHES = ["Poseidon", "Poseidon2", "Sha256"]
const HASHTITLE = {
    Poseidon: "chance's poseidon (PoseidonT3)",
    Poseidon2: "zemse's poseidon2Yul",
    Sha256: "sha256"
}
const commas = (n) => n.toLocaleString("en-US")
const gk = (d) => {
    const s = d >= 0 ? "+" : "−"
    const a = Math.abs(d)
    return a >= 1000 ? `${s}${Math.round(a / 1000)}k` : `${s}${a}`
}
const pct = (v, base) => {
    const p = ((v - base) / base) * 100
    return (p >= 0 ? "+" : "") + p.toFixed(1)
}
const cell = (v, base) => `${commas(v)} (${pct(v, base)}%, ${gk(v - base)})`

// Everything ABOVE this marker is hand-editable prose that the script preserves across regenerations;
// everything below it (the tables + numeric footnotes) is regenerated each run.
const MARK = "<!-- BEGIN GENERATED: regenerated by scripts/gen-gas-comparison.mjs — edit prose ABOVE this line -->"

// Default intro, used only when GAS_COMPARISON.md doesn't exist yet (or has no marker). Once the file
// has the marker, the real prose above it is kept verbatim instead of this.
const DEFAULT_INTRO = `# IMT gas comparison — bare / event / full vs vanilla lean-IMT

All numbers are on-chain \`gasUsed\` for one transaction, measured on matched scenarios (same tree sizes, same ops). Optimizer \`runs: 2**32-1\` on every package. The three **versions** differ only in how a tree's leaves are made available to off-chain clients:

- **bare** — leaves stored **nowhere** (no events, no array). Just like in the original lean-imt.
- **event** — leaves emitted as \`NewLeaf\` **logs** (the current production \`SkinnyIMTPoseidon\` / \`FatIMTPoseidon\`).
- **full** — leaves persisted in a **storage array** _and_ emitted as logs (\`…FullNode\`), so clients can read them from state (\`eth_getStorageAt\` / \`debug_storageRangeAt\` / \`getLeaves()\`).

Every cell shows \`gasUsed (Δ% vs lean, Δgas vs lean)\`, compared against the single **vanilla lean-IMT / PoseidonT3** baseline (lean has no poseidon2Yul/sha256 build, so it anchors all three).

`

const out = []
out.push("### vanilla lean-IMT baseline (PoseidonT3)\n")
out.push("| " + KEYS.map((k) => ROWLBL[k]).join(" | ") + " |")
out.push("|" + KEYS.map(() => "--:").join("|") + "|")
out.push("| " + KEYS.map((k) => commas(LEAN[k])).join(" | ") + " |")
out.push("")
for (const pkg of ["skinny", "fat"]) {
    out.push(`## ${pkg}-IMT\n`)
    for (const h of HASHES) {
        out.push(`### ${pkg} — ${HASHTITLE[h]}\n`)
        out.push("| Scenario | bare (floor) | event (logs) | full (storage+logs) |")
        out.push("|---|--:|--:|--:|")
        for (const k of KEYS) {
            const base = LEAN[k]
            const b = DATA[pkg][h].Bare[k]
            const e = DATA[pkg][h].Event[k]
            const f = DATA[pkg][h].Full[k]
            out.push(`| ${ROWLBL[k]} | ${cell(b, base)} | ${cell(e, base)} | ${cell(f, base)} |`)
        }
        out.push("")
    }
}
out.push(
    "† `insertManyRepeated` is apples-to-oranges: skinny/fat insert 128 **identical** leaves via their " +
        "optimized repeated-insert path; lean forbids zero/duplicate leaves so its stand-in inserts 128 **distinct** " +
        'leaves via `insertMany` (~128× the hashing). The row measures "lean has no repeated-insert primitive," not ' +
        "a like-for-like op.\n"
)

// Preserve any hand-edited prose above the marker; only the generated block is rewritten.
const mdPath = join(ROOT, "GAS_COMPARISON.md")
let prefix = DEFAULT_INTRO
if (existsSync(mdPath)) {
    const existing = readFileSync(mdPath, "utf8")
    const at = existing.indexOf(MARK)
    if (at !== -1) prefix = existing.slice(0, at)
}
writeFileSync(mdPath, prefix + MARK + "\n\n" + out.join("\n"))

// Format so the committed result is stable (the pre-commit hook runs prettier anyway).
try {
    execFileSync(join(ROOT, "node_modules", ".bin", "prettier"), ["--write", "GAS_COMPARISON.md"], {
        cwd: ROOT,
        stdio: "ignore"
    })
} catch {
    console.error("  (prettier not run — commit hook will format it)")
}
console.error("\n✓ wrote GAS_COMPARISON.md")
